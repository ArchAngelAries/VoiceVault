r"""
Whisper on the GPU. Skipped unless VV_GPU_TESTS=1 and the sample clips exist.

Samples are generated by the Maya1 adapter (see tests/test_maya1_gpu.py and the verification
notes in docs/DEVELOPMENT_STATUS.md). The long-form sample is the 61 s, 14-sentence recording
from 2026-10-09; the test looks for its sentences, in order, in the timestamped output.

Run from backend/:  set VV_GPU_TESTS=1 && ..\venv\Scripts\python.exe -m pytest tests/test_asr_gpu.py -s
"""
import os
import time
from pathlib import Path

import pytest

OUTPUTS = Path(__file__).resolve().parents[2] / "data" / "outputs"
SHORT_SAMPLES = sorted(OUTPUTS.glob("*.wav"))
LONG_SAMPLE = Path(__file__).resolve().parents[2] / "data" / "test_audio" / "long_form_61s.wav"

GPU_ENABLED = os.environ.get("VV_GPU_TESTS") == "1"
needs_gpu = pytest.mark.skipif(not GPU_ENABLED, reason="GPU test: set VV_GPU_TESTS=1")

LONG_SENTENCES = [
    "quick brown fox", "library now tracks", "back up the database", "weather will be cool",
    "fifth one", "timestamps for the start", "long-form handling", "sidecar record",
    "one large model", "split long recordings", "dataset preparation", "radeon rx 7900",
    "single pass", "end of the test",
]


@needs_gpu
@pytest.mark.skipif(not SHORT_SAMPLES, reason="no generated clip in data/outputs")
def test_whisper_transcribes_a_short_clip_on_the_gpu():
    import torch

    from asr.audio import decode_audio
    from asr.whisper_engine import WhisperTranscriber

    assert torch.cuda.is_available(), "PyTorch cannot see the GPU; this is not a ROCm run"
    transcriber = WhisperTranscriber()
    assert transcriber.runtime_problem() is None

    t0 = time.time()
    transcriber.load(device="cuda", dtype="float16")
    load_s = time.time() - t0
    try:
        result = transcriber.transcribe(decode_audio(SHORT_SAMPLES[0]), language="en")
    finally:
        transcriber.unload()

    print(f"\nload {load_s:.1f}s | {result['duration_s']}s audio | RTF {result['real_time_factor']} | "
          f"text: {result['text']!r} | segments: {len(result['segments'])}")
    text = result["text"].lower()
    assert "gpu" in text
    assert "vault" in text
    assert result["device"] == "cuda"
    assert result["segments"] and result["segments"][0]["end"] > 0


@needs_gpu
@pytest.mark.skipif(not SHORT_SAMPLES, reason="no generated clip in data/outputs")
def test_whisper_detects_the_language_of_a_short_clip_when_none_is_given():
    from asr.audio import decode_audio
    from asr.whisper_engine import WhisperTranscriber

    transcriber = WhisperTranscriber()
    transcriber.load(device="cuda", dtype="float16")
    try:
        result = transcriber.transcribe(decode_audio(SHORT_SAMPLES[0]), language=None, timestamps=False)
    finally:
        transcriber.unload()

    assert "vault" in result["text"].lower()


@needs_gpu
@pytest.mark.skipif(not LONG_SAMPLE.is_file(), reason="long-form sample missing from data/outputs")
def test_whisper_long_form_keeps_every_sentence_and_its_timing():
    from asr.audio import decode_audio
    from asr.whisper_engine import WhisperTranscriber

    transcriber = WhisperTranscriber()
    transcriber.load(device="cuda", dtype="float16")
    try:
        result = transcriber.transcribe(decode_audio(LONG_SAMPLE), language="en", timestamps=True)
    finally:
        transcriber.unload()

    text = result["text"].lower()
    missing = [phrase for phrase in LONG_SENTENCES if phrase not in text]
    assert not missing, f"phrases lost in long-form output: {missing}"
    starts = [seg["start"] for seg in result["segments"]]
    assert starts == sorted(starts), "segments are out of order"
    assert result["segments"][-1]["end"] > 55.0, "output stops early"
    assert all(seg["end"] - seg["start"] < 12.0 for seg in result["segments"]), "a segment spans too much audio"
